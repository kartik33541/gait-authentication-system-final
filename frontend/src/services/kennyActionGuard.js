/**
 * @file kennyActionGuard.js
 * @description Agent 4: The Action & Mutation Guard (Human-in-the-Loop Controller).
 * Enforces a strict Two-Phase Commit (2PC) State Machine.
 * NEVER executes autonomous destructive mutations. All state changes require physical admin confirmation in chat.
 */

import { db } from '../firebase.js';
import { 
  doc, 
  getDoc,
  updateDoc, 
  addDoc, 
  collection, 
  serverTimestamp 
} from 'firebase/firestore';
import { searchEmployeeRoster } from './kennyDbService.js';
import toast from 'react-hot-toast';

const GATE_MODE_CONFIG = {
  HIGH_THROUGHPUT: { mode: 'HIGH_THROUGHPUT', threshold: 0.65, label: 'Smooth & Easy' },
  BALANCED: { mode: 'BALANCED', threshold: 0.75, label: 'Balanced' },
  STRICT: { mode: 'STRICT', threshold: 0.85, label: 'Strict & High Security' }
};

const resolveStrictnessChoice = (args = {}) => {
  const combined = `${args.mode || ''} ${args.target_name || ''} ${args.details || ''}`.toUpperCase();
  if (combined.includes('HIGH_THROUGHPUT') || combined.includes('SMOOTH') || combined.includes('LOW') || combined.includes('0.65')) {
    return GATE_MODE_CONFIG.HIGH_THROUGHPUT;
  }
  if (combined.includes('STRICT') || combined.includes('HIGH') || combined.includes('MAX') || combined.includes('0.85')) {
    return GATE_MODE_CONFIG.STRICT;
  }
  return GATE_MODE_CONFIG.BALANCED;
};

// Strict Whitelist of proposable actions
export const ALLOWED_ACTIONS = [
  'PAUSE_EMPLOYEE',
  'RESUME_EMPLOYEE',
  'SET_GATE_STRICTNESS',
  'DISMISS_INCIDENT',
  'ESCALATE_INCIDENT'
];

// Strict Blacklist of strictly forbidden actions (Must use manual UI modal)
export const FORBIDDEN_ACTIONS = [
  'DELETE_EMPLOYEE',
  'DELETE_ORGANIZATION',
  'OVERWRITE_READINGS',
  'EMERGENCY_LOCKDOWN'
];

/**
 * Phase 1: Propose Action (Generated by LLM request, zero DB write)
 */
export const proposeAction = async (args, context = {}) => {
  const rawAction = (args.action || '').toUpperCase().trim();
  const targetName = args.target_name || args.target_id || 'Employee';
  const tenantId = context.tenantId;
  const timestamp = new Date().toLocaleTimeString();

  if (!tenantId) {
    return {
      dispatchedAgent: 'Kenny',
      timestamp,
      isForbidden: true,
      actionCard: null,
      message: 'Authentication session required to propose security actions.'
    };
  }

  // Check Forbidden Actions first
  for (const forbidden of FORBIDDEN_ACTIONS) {
    if (rawAction.includes(forbidden) || rawAction.includes('DELETE') || rawAction.includes('OVERWRITE')) {
      return {
        dispatchedAgent: 'Kenny',
        timestamp,
        isForbidden: true,
        actionCard: null,
        message: [
          `### ⛔ Security Policy Guard Active`,
          ``,
          `* **Requested Action:** \`${rawAction}\``,
          `* **Safety Rule:** Irreversible destructive operations cannot be executed via chat.`,
          ``,
          `For data security and legal compliance, permanent deletion and data overwrites must be performed manually through the designated dashboard modal with dual-confirmation safeguards.`
        ].join('\n')
      };
    }
  }

  // Determine which allowed action is being proposed
  let actionType = 'PAUSE_EMPLOYEE';
  let title = 'Suspend Door Access';
  let confirmLabel = 'Confirm Pause Access';
  let warning = 'All perimeter turnstiles will immediately stop this person from entering.';
  let resolvedTargetId = args.target_id || null;
  let resolvedTargetName = targetName;

  // Resolve employee ID if searching by name
  if (rawAction.includes('RESUME') || rawAction.includes('UNPAUSE') || rawAction.includes('ACTIVATE')) {
    actionType = 'RESUME_EMPLOYEE';
    title = `Restore Door Access: ${targetName}`;
    confirmLabel = 'Confirm Restore Access';
    warning = 'This person will immediately be authorized to unlock perimeter doors with their passkey.';
  } else if (rawAction.includes('STRICT') || rawAction.includes('THRESHOLD') || rawAction.includes('POLICY')) {
    actionType = 'SET_GATE_STRICTNESS';
    title = `Update Gate Strictness Policy`;
    confirmLabel = 'Apply Strictness Policy';
    warning = 'This will adjust perimeter threshold sensitivity across all physical IoT door nodes.';
  } else if (rawAction.includes('DISMISS')) {
    actionType = 'DISMISS_INCIDENT';
    title = `Dismiss Flagged Incident (False Alarm)`;
    confirmLabel = 'Confirm False Alarm';
    warning = 'This event will be marked resolved and will decrement the Morning Health Check flagged count.';
  } else {
    // Default: PAUSE_EMPLOYEE
    actionType = 'PAUSE_EMPLOYEE';
    title = `Suspend Door Access: ${targetName}`;
    confirmLabel = 'Confirm Pause Access';
    warning = 'All perimeter turnstiles will immediately stop this person from entering.';
  }

  // Cross-reference employee in DB if employee action
  if (actionType === 'PAUSE_EMPLOYEE' || actionType === 'RESUME_EMPLOYEE') {
    const searchResult = await searchEmployeeRoster(tenantId, targetName);
    if (searchResult.found) {
      resolvedTargetId = searchResult.matchedEmployee.id || searchResult.matchedEmployee.template_id;
      resolvedTargetName = searchResult.matchedEmployee.name;
    }
  }

  const strictnessChoice = actionType === 'SET_GATE_STRICTNESS' ? resolveStrictnessChoice(args) : null;
  if (strictnessChoice) {
    resolvedTargetId = tenantId;
    resolvedTargetName = `${strictnessChoice.label} (${strictnessChoice.threshold})`;
  }

  const actionPayload = {
    actionId: `ACT_${Date.now()}`,
    actionType,
    targetName: resolvedTargetName,
    targetId: resolvedTargetId || 'EMP-001',
    mode: strictnessChoice?.mode || null,
    threshold: strictnessChoice?.threshold || null,
    title,
    warning,
    confirmLabel,
    tenantId,
    status: 'PENDING_CONFIRMATION'
  };

  return {
    dispatchedAgent: 'Kenny',
    timestamp,
    isForbidden: false,
    actionCard: actionPayload,
    message: [
      `### 🛡️ Action Proposed: Admin Confirmation Required`,
      ``,
      `* **Action:** \`${actionType}\``,
      `* **Target:** **${resolvedTargetName}** (ID: \`${actionPayload.targetId}\`)`,
      ``,
      `**Warning:** ${warning}`,
      ``,
      `*Review the proposal below and click the button to execute the state change:*`
    ].join('\n')
  };
};

/**
 * Phase 2: Execute Confirmed Action (Triggered ONLY by human physical button click in UI)
 */
export const executeConfirmedAction = async (actionCard) => {
  if (!actionCard || !actionCard.actionType) {
    throw new Error("Invalid action card payload");
  }

  const tenantId = actionCard.tenantId;
  if (!tenantId) {
    throw new Error("Unauthorized action: missing organization context");
  }
  const targetId = actionCard.targetId;

  try {
    if (actionCard.actionType === 'PAUSE_EMPLOYEE') {
      const empRef = doc(db, 'organizations', tenantId, 'employees', targetId);
      await updateDoc(empRef, {
        status: 'PAUSED',
        updated_at: serverTimestamp()
      });

      // Log in access audit trail
      const logsRef = collection(db, 'organizations', tenantId, 'access_logs');
      await addDoc(logsRef, {
        tenant_id: tenantId,
        timestamp: serverTimestamp(),
        employee_id: targetId,
        employee_name: actionCard.targetName,
        status: 'DENIED',
        confidence_score: '0%',
        walk_energy: 0,
        reason: 'Access paused by admin via Kenny AI',
        gate_id: 'SYSTEM_ADMIN_OVERRIDE',
        incident_status: 'RESOLVED'
      });

      toast.success(`Access paused for ${actionCard.targetName}`);
      return { success: true, message: `Access paused for ${actionCard.targetName}` };

    } else if (actionCard.actionType === 'RESUME_EMPLOYEE') {
      const empRef = doc(db, 'organizations', tenantId, 'employees', targetId);
      await updateDoc(empRef, {
        status: 'ACTIVE',
        updated_at: serverTimestamp()
      });

      toast.success(`Access restored for ${actionCard.targetName}`);
      return { success: true, message: `Access restored for ${actionCard.targetName}` };

    } else if (actionCard.actionType === 'SET_GATE_STRICTNESS') {
      const choice = resolveStrictnessChoice(actionCard);
      const orgRef = doc(db, 'organizations', tenantId);
      const orgSnap = await getDoc(orgRef);
      const existingAutoNight = orgSnap.exists()
        ? (orgSnap.data()?.security_policy?.auto_night_strict ?? true)
        : true;

      await updateDoc(orgRef, {
        security_policy: {
          strictness_mode: choice.mode,
          threshold: choice.threshold,
          auto_night_strict: existingAutoNight,
          updated_at: new Date().toISOString(),
          updated_by: 'Kenny AI'
        }
      });

      const logsRef = collection(db, 'organizations', tenantId, 'access_logs');
      await addDoc(logsRef, {
        tenant_id: tenantId,
        employee_id: 'POLICY',
        employee_name: 'Kenny AI Policy Guard',
        status: 'GRANTED',
        confidence_score: '100%',
        walk_energy: 0,
        reason: `Door sensitivity set to ${choice.label}`,
        ai_diagnosis: `Administrator confirmed Kenny AI policy update to ${choice.label} (threshold: ${choice.threshold}).`,
        timestamp: serverTimestamp()
      });

      toast.success(`Door sensitivity updated: ${choice.label}`);
      return { success: true, message: `Door sensitivity updated to ${choice.label} (${choice.threshold})` };

    } else if (actionCard.actionType === 'DISMISS_INCIDENT') {
      const logRef = doc(db, 'organizations', tenantId, 'access_logs', targetId);
      await updateDoc(logRef, {
        incident_status: 'DISMISSED',
        resolution_note: 'Dismissed as false alarm via Kenny AI'
      });

      toast.success("Incident marked as false alarm");
      return { success: true, message: "Incident marked as false alarm" };
    }

    throw new Error(`Unsupported action type: ${actionCard.actionType}`);
  } catch (err) {
    console.error("Action execution error:", err);
    toast.error(`Action failed: ${err.message}`);
    throw err;
  }
};
